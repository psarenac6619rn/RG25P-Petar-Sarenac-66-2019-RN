GUI::GUI(int screenWidth, int screenHeight) : W(screenWidth), H(screenHeight) {
    shader = new Shader("shaders/gui.vert", "shaders/gui.frag");
    initFont();

    glGenVertexArrays(1, &vao);
    glGenBuffers(1, &vbo);
    glBindVertexArray(vao);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    // x, y, u, v
    glBufferData(GL_ARRAY_BUFFER, sizeof(float) * 4 * 6 * 256, nullptr, GL_DYNAMIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));
    glBindVertexArray(0);
}

GUI::~GUI() {
    delete shader;
    glDeleteVertexArrays(1, &vao);
    glDeleteBuffers(1, &vbo);
    glDeleteTextures(1, &fontTex);
}

void GUI::resize(int w, int h) {
    W = w;
    H = h;
}

void GUI::initFont() {
    // Unpack bits into a 1D texture for 128 chars, each 8x8
    // We create a texture of size 1024 x 8 where each char is 8x8 next to each other
    const int texW = 128 * 8;
    const int texH = 8;
    std::vector<unsigned char> pixels(texW * texH, 0);

    for (int c = 0; c < 128; c++) {
        for (int y = 0; y < 8; y++) {
            unsigned char row = font8x8[c][y];
            for (int x = 0; x < 8; x++) {
                if (row & (1 << x)) {
                    // Bitmap stores pixels horizontally. (1<<x) is the bit.
                    pixels[y * texW + (c * 8 + x)] = 255;
                }
            }
        }
    }

    glGenTextures(1, &fontTex);
    glBindTexture(GL_TEXTURE_2D, fontTex);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RED, texW, texH, 0, GL_RED, GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
}

void GUI::begin() {
    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    shader->use();
    Mat4 ortho = orthographic(0.0f, (float)W, (float)H, 0.0f, -1.0f, 1.0f);
    shader->setMat4("projection", ortho);
    shader->setMat4("model", identity());
}

void GUI::end() {
    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);
}

void GUI::drawCrosshair() {
    shader->setVec3("textColor", {1.0f, 1.0f, 1.0f});
    shader->setInt("hasTex", 0);

    float cx = W / 2.0f;
    float cy = H / 2.0f;
    float size = 8.0f;
    float thick = 2.0f;

    float vertices[] = {
        // horizontal line
        cx - size, cy - thick/2.0f, 0.0f, 0.0f,
        cx + size, cy - thick/2.0f, 0.0f, 0.0f,
        cx + size, cy + thick/2.0f, 0.0f, 0.0f,
        cx + size, cy + thick/2.0f, 0.0f, 0.0f,
        cx - size, cy + thick/2.0f, 0.0f, 0.0f,
        cx - size, cy - thick/2.0f, 0.0f, 0.0f,
        // vertical line
        cx - thick/2.0f, cy - size, 0.0f, 0.0f,
        cx + thick/2.0f, cy - size, 0.0f, 0.0f,
        cx + thick/2.0f, cy + size, 0.0f, 0.0f,
        cx + thick/2.0f, cy + size, 0.0f, 0.0f,
        cx - thick/2.0f, cy + size, 0.0f, 0.0f,
        cx - thick/2.0f, cy - size, 0.0f, 0.0f
    };

    glBindVertexArray(vao);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(vertices), vertices);
    glDrawArrays(GL_TRIANGLES, 0, 12);
}

void GUI::drawText(const std::string& text, float x, float y, float scale, Vec3 color) {
    shader->setVec3("textColor", color);
    shader->setInt("hasTex", 1);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, fontTex);
    shader->setInt("text", 0);

    std::vector<float> vertices;
    vertices.reserve(text.length() * 6 * 4);

    float px = x;
    for (char c : text) {
        if (c < 0 || c > 127) c = '?';
        
        float u0 = (c * 8.0f) / (128.0f * 8.0f);
        float u1 = ((c + 1) * 8.0f) / (128.0f * 8.0f);
        float v0 = 0.0f;
        float v1 = 1.0f;

        float xpos = px;
        float ypos = y;
        float w = 8.0f * scale;
        float h = 8.0f * scale;

        vertices.push_back(xpos);     vertices.push_back(ypos + h); vertices.push_back(u0); vertices.push_back(v1);
        vertices.push_back(xpos + w); vertices.push_back(ypos);     vertices.push_back(u1); vertices.push_back(v0);
        vertices.push_back(xpos);     vertices.push_back(ypos);     vertices.push_back(u0); vertices.push_back(v0);

        vertices.push_back(xpos);     vertices.push_back(ypos + h); vertices.push_back(u0); vertices.push_back(v1);
        vertices.push_back(xpos + w); vertices.push_back(ypos + h); vertices.push_back(u1); vertices.push_back(v1);
        vertices.push_back(xpos + w); vertices.push_back(ypos);     vertices.push_back(u1); vertices.push_back(v0);

        px += 8.0f * scale;
    }

    glBindVertexArray(vao);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    glBufferSubData(GL_ARRAY_BUFFER, 0, vertices.size() * sizeof(float), vertices.data());
    glDrawArrays(GL_TRIANGLES, 0, (GLsizei)(vertices.size() / 4));
}
